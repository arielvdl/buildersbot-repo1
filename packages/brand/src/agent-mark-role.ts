/** The role symbol for an agent's title, or `null` to keep the scribbled face. */
export function avatarMarkRole(title: string | null | undefined): AgentMarkRole | null {
  if (!title) return null;
  const words = title
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .split(/[^a-z0-9]+/u)
    .filter(Boolean);
  if (words.length === 0) return null;
  for (const role of AGENT_MARK_ROLES) {
    const matches = ROLE_STEMS[role].some((stem) =>
      words.some((word) => (stem.length <= 3 ? word === stem : word.startsWith(stem))),
    );
    if (matches) return role;
  }
  return null;
}
